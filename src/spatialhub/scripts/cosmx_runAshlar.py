"""
Run Ashlar on a set of full-grid tiles generated by `cosmx_organiseFields.py`.

Outputs
-------
- A stitched OME-TIFF file of the field tiles.
- A CSV file with the positions and shifts of the field tiles.

This script is adapted from https://gist.github.com/jmuhlich/59e114243278cf27e7f0720c2c956484.
"""

import os
import numpy as np
import pandas as pd

from argparse import ArgumentParser as AP
from ashlar.fileseries import FileSeriesReader
from ashlar.reg import EdgeAligner, Mosaic, PyramidWriter
from spatialhub.scripts.utils import GREEN, RESET, print_arguments, die


def main():
    p = AP(description="Run Ashlar on CosMx FOV tiles.")
    p.add_argument("outdir", help="Directory for the output files.")
    p.add_argument("--gridpos-csv", required=True, help="Grid position CSV file.")
    p.add_argument("--field-dir", required=True, help="Field directory for stitching.")
    p.add_argument("--name-pattern", required=True, help="Pattern for FOV filenames.")
    p.add_argument("--px-size", type=float, default=0.120280945, help="Pixel size.")
    p.add_argument("--overlap", type=float, default=0.01, help="FOV overlap fraction.")
    p.add_argument("--max-shift", type=int, default=15, help="Maximum shift (µm).")
    p.add_argument("--ch-align", type=int, default=0, help="Channel for alignment.")
    p.add_argument("--ch-out", default=None, help="Comma-separated channels to output.")
    args = p.parse_args()
    print_arguments(args)

    out_csv = os.path.join(args.outdir, "FOV.positions.csv")
    out_tiff = os.path.join(args.outdir, "image.ome.tiff")
    if os.path.exists(out_csv) or os.path.exists(out_tiff):
        raise FileExistsError(f"output file '{out_csv}' or '{out_tiff}' already exists")
    outdir = os.path.dirname(out_tiff)
    if outdir:
        os.makedirs(outdir, exist_ok=True)
    print(f"Output files will be written to '{out_csv}' and '{out_tiff}'.")

    if not os.path.exists(args.gridpos_csv):
        raise FileNotFoundError(f"Grid position file '{args.gridpos_csv}' not found")
    gridpos = pd.read_csv(args.gridpos_csv)

    # Validate grid index column and uniqueness
    if "grid_index" not in gridpos.columns:
        raise ValueError("'grid_index' column is required in grid position CSV")
    gridpos.set_index("grid_index", inplace=True)
    if not gridpos.index.is_unique:
        raise ValueError("Duplicate grid_index detected")

    # Validate required FOV, col_index, and row_index columns
    required_cols = {"FOV", "col_index", "row_index", "x_global_px", "y_global_px"}
    missing = required_cols - set(gridpos.columns)
    if missing:
        raise ValueError(f"Missing {', '.join(sorted(missing))}s in grid position CSV")

    # Validate directory for field symbolic links
    if not os.path.isdir(args.field_dir):
        raise FileNotFoundError(f"field directory '{args.field_dir}' does not exist")

    # Parse channels to write
    ch_lst = list(map(int, args.ch_out.split(","))) if args.ch_out is not None else None

    # Determine grid dimensions
    ncols, nrows = gridpos["col_index"].max() + 1, gridpos["row_index"].max() + 1
    print(f"Parsed grid dimensions: {ncols} columns x {nrows} rows.")
    grid2meta = gridpos[["FOV", "x_global_px", "y_global_px"]].to_dict(orient="index")

    # Read the field tiles using FileSeriesReader
    reader = FileSeriesReader(
        args.field_dir,
        pattern=args.name_pattern,
        width=ncols,
        height=nrows,
        overlap=args.overlap,
        pixel_size=args.px_size,
    )
    nfiles, ngrids = reader.metadata.num_images, len(grid2meta)
    if nfiles != ngrids:
        raise ValueError(f"field number mismatch: {nfiles} files but {ngrids} rows")

    # Generate corrected positions from CosMx coordinates rather than strictly regular grid positions
    # (necessary to handle the case of shifted FOVs between big gaps in the grid).

    # Convert CosMx coordinates into a common coordinate system
    # with X increasing rightwards and Y increasing downwards.
    x = gridpos["x_global_px"].to_numpy(dtype=float)
    y = gridpos["y_global_px"].to_numpy(dtype=float)

    x = x - x.min()
    y = y.max() - y

    # Apply overlap correction
    scale = 1.0 - args.overlap
    corrected_positions = np.column_stack([y * scale, x * scale])

    # Ensure positions follow ASHLAR's image-series ordering
    series_indices = [s for _, s in reader.metadata.all_series]
    indices = gridpos.index.get_indexer(series_indices)
    if np.any(indices < 0):
        raise ValueError("ASHLAR series indices missing from grid positions")

    corrected_positions = corrected_positions[indices]

    print("Original ASHLAR positions:")
    print(reader.metadata.positions[:10])

    print("Corrected CosMx positions:")
    print(corrected_positions[:10])

    assert corrected_positions.shape == reader.metadata.positions.shape
    assert np.isfinite(corrected_positions).all()

    # Replace FileSeriesReader's regular-grid positions
    reader.metadata._positions = corrected_positions

    print("Updated ASHLAR positions match expected format:")
    print(np.allclose(reader.metadata.positions, corrected_positions))
    

    # Align the field tiles using EdgeAligner
    aligner = EdgeAligner(reader, channel=args.ch_align, max_shift=args.max_shift)

    # Debugging purposes:
    # Summarise the candidate neighbour pairs and their physical overlap
    positions = reader.metadata.positions
    tile_size = reader.metadata.size
    edges = list(aligner.neighbors_graph.edges())

    print(f"Tile size (Y, X): {tile_size}")
    print(f"Number of candidate neighbour pairs: {len(edges)}")

    if edges:
        pairs = np.asarray(edges, dtype=int)
        delta = np.abs(
            positions[pairs[:, 0]] - positions[pairs[:, 1]]
        )
        overlap = tile_size - delta
        valid = np.all(overlap > 0, axis=1)

        print("Pairs with physical overlap:", valid.sum())
        print("Pairs without physical overlap:", (~valid).sum())

        if valid.any():
            print(
                "Median overlap (Y, X), pixels:",
                np.median(overlap[valid], axis=0)
            )

    # Run the alignment process
    aligner.run()

    # Debugging purposes:
    # Summarise alignment results
    shifts = np.asarray(aligner.shifts)

    print("Number of tiles:", len(shifts))
    print("Number of neighbouring tile pairs:",
        aligner.neighbors_graph.number_of_edges())

    print("Number of registered pairs:",
        sum(np.isfinite(error) for _, error in aligner._cache.values()))

    print("Shift range (pixels):")
    print("  Y:", shifts[:, 0].min(), shifts[:, 0].max())
    print("  X:", shifts[:, 1].min(), shifts[:, 1].max())

    print("Tiles with non-zero shifts:",
        np.count_nonzero(np.any(np.abs(shifts) > 0.01, axis=1)))


    # Write out the stitched mosaic to an OME-TIFF file
    mosaic = Mosaic(aligner, aligner.mosaic_shape, channels=ch_lst)
    writer = PyramidWriter([mosaic], out_tiff)
    writer.run()
    print(f"Wrote output to '{out_tiff}'.")

    # Write out the positions and shifts to a CSV file
    coords_df = pd.DataFrame(
        np.hstack([aligner.positions, aligner.shifts]),
        columns=["Position_Y", "Position_X", "Shift_Y", "Shift_X"],
        index=pd.Series([s for _, s in reader.metadata.all_series], name="grid_index"),
    ).round(5)
    coords_df["FOV"] = coords_df.index.map(lambda x: grid2meta[x]["FOV"])
    coords_df["x_global_px"] = coords_df.index.map(
        lambda x: grid2meta[x]["x_global_px"]
    )
    coords_df["y_global_px"] = coords_df.index.map(
        lambda x: grid2meta[x]["y_global_px"]
    )
    coords_df = coords_df.loc[coords_df["FOV"] >= 0].copy()  # Exclude mock FOVs
    coords_df = coords_df[
        [
            "FOV",
            "Position_X",
            "Position_Y",
            "Shift_X",
            "Shift_Y",
            "x_global_px",
            "y_global_px",
        ]
    ]
    coords_df.set_index("FOV").to_csv(out_csv)
    print(f"Wrote output to '{out_csv}'.")

    print(f"{GREEN}Ashlar completed successfully.{RESET}")


if __name__ == "__main__":
    try:
        main()
    except Exception:
        die("Failed to run Ashlar.")
